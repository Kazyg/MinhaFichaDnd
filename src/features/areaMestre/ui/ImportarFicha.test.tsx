import { fireEvent, render, screen, waitFor } from '@testing-library/react';
import ImportarFicha from './ImportarFicha';
import { Ficha } from '../../../api/fichaPersonagem/FichaPersonagem';
import { exportFicha } from '../../../api/fichaPersonagem/fichaStorage';
import { gerarFichaPdf } from '../../../utils/exportarFichaPdf';
import { reconhecerArquivo } from '../reconhecimento';
jest.mock('./VisualizadorDocumento', () => ({ __esModule: true, default: () => <p>Prévia original</p> }));
jest.mock('../../../utils/exportarFichaPdf', () => ({ gerarFichaPdf: jest.fn(async () => new Uint8Array([37,80,68,70,45])) }));
jest.mock('../reconhecimento', () => ({ reconhecerArquivo: jest.fn(async (anexo: {mime:string}) => anexo.mime === 'application/pdf' ? {nome:'Goblin',pv:{atuais:7,maximos:7},avisos:[]} : {nome:null,pv:null,avisos:['PV não identificados']}) }));

describe('modal de importação', () => {
  let anterior: PropertyDescriptor | undefined;
  beforeEach(() => { anterior = Object.getOwnPropertyDescriptor(globalThis, 'crypto'); let n = 0; Object.defineProperty(globalThis, 'crypto', { configurable: true, value: { randomUUID: () => `id-${++n}` } });
    (gerarFichaPdf as jest.Mock).mockResolvedValue(new Uint8Array([37,80,68,70,45]));
    (reconhecerArquivo as jest.Mock).mockImplementation(async (anexo: {mime:string}) => anexo.mime === 'application/pdf' ? {nome:'Goblin',pv:{atuais:7,maximos:7},avisos:[]} : {nome:null,pv:null,avisos:['PV não identificados']});
  });
  afterEach(() => { if (anterior) Object.defineProperty(globalThis, 'crypto', anterior); });
  const selecionar = () => {
    const arquivo = new File([exportFicha(new Ficha({ id:'x', nomePersonagem:'Aria', vidaTotal:20, vidaAtual:12 }))], 'aria.json', { type: 'application/json' });
    fireEvent.change(screen.getByLabelText(/Arquivo da ficha/), { target: { files: [arquivo] } });
    return arquivo;
  };
  test('prévia e cancelamento não confirmam nem criam registros', async () => {
    const confirmar = jest.fn(), fechar = jest.fn();
    render(<ImportarFicha categoria="jogador" campanhaId="c" onConfirmar={confirmar} onFechar={fechar} />);
    selecionar(); await screen.findByLabelText('Nome da ficha');
    expect(screen.queryByText('Prévia original')).not.toBeInTheDocument();
    expect(screen.getByText('Arquivo: aria.json')).toBeInTheDocument();
    expect(screen.getByLabelText('Nome da ficha')).toHaveValue('Aria');
    expect(screen.getByLabelText('PV máximos')).toHaveValue(20);
    fireEvent.click(screen.getByText('Cancelar'));
    expect(fechar).toHaveBeenCalledTimes(1); expect(confirmar).not.toHaveBeenCalled();
  });
  test('revisa valores e permite tentar salvar novamente com os mesmos IDs e bytes', async () => {
    const confirmar = jest.fn().mockResolvedValueOnce(false).mockResolvedValueOnce(true), fechar = jest.fn();
    render(<ImportarFicha categoria="jogador" campanhaId="c" onConfirmar={confirmar} onFechar={fechar} />);
    const arquivo = selecionar(); await screen.findByLabelText('Nome da ficha');
    fireEvent.change(screen.getByLabelText('PV atuais'), { target: { value: '21' } });
    fireEvent.click(screen.getByText('Incluir'));
    await screen.findByRole('alert'); expect(confirmar).not.toHaveBeenCalled();
    fireEvent.change(screen.getByLabelText('PV atuais'), { target: { value: '9' } });
    fireEvent.click(screen.getByText('Incluir'));
    await screen.findByText(/Sua importação permanece/);
    expect(fechar).not.toHaveBeenCalled();
    fireEvent.click(screen.getByText('Incluir'));
    await waitFor(() => expect(fechar).toHaveBeenCalled());
    expect(confirmar.mock.calls[0][0].ficha.id).toBe(confirmar.mock.calls[1][0].ficha.id);
    expect(confirmar.mock.calls[1][0].anexos[0].arquivo).toBe(arquivo);
    expect(confirmar.mock.calls[1][0].ficha.pvIniciais).toEqual({ atuais: 9, maximos: 20 });
    expect(screen.getByLabelText(/Arquivo da ficha/)).toBeDisabled();
  });
  test('falha de geração não permite incluir e oferece repetir o mesmo arquivo', async () => {
    (gerarFichaPdf as jest.Mock).mockRejectedValueOnce(new Error('Template indisponível'));
    const confirmar=jest.fn();
    render(<ImportarFicha categoria="jogador" campanhaId="c" onConfirmar={confirmar} onFechar={jest.fn()} />);
    selecionar();
    expect(await screen.findByRole('alert')).toHaveTextContent('Template indisponível');
    expect(screen.getByRole('button',{name:'Incluir'})).toBeDisabled();
    expect(confirmar).not.toHaveBeenCalled();
    fireEvent.click(screen.getByRole('button',{name:'Tentar preparar arquivo novamente'}));
    await screen.findByLabelText('Nome da ficha');
    expect(screen.getByRole('button',{name:'Incluir'})).toBeEnabled();
  });
  test('PDF usa texto conservador e retrato separado sem alterar o original', async () => {
    const confirmar = jest.fn().mockResolvedValue(true);
    render(<ImportarFicha categoria="monstro" campanhaId="c" onConfirmar={confirmar} onFechar={jest.fn()} />);
    const pdf = new File(['%PDF-1.7 original'], 'documento.pdf', { type: 'application/pdf' });
    fireEvent.change(screen.getByLabelText(/Arquivo da ficha/), { target: { files: [pdf] } });
    await screen.findByLabelText('Nome da ficha');
    await waitFor(() => expect(screen.getByLabelText('Nome da ficha')).toHaveValue('Goblin'));
    expect(screen.getByLabelText('PV máximos')).toHaveValue(7);
    const imagem = new File([new Uint8Array([137, 80, 78, 71, 13, 10, 26, 10])], 'goblin.png', { type: 'image/png' });
    fireEvent.change(screen.getByLabelText('Retrato opcional'), { target: { files: [imagem] } });
    await screen.findByText('Remover retrato');
    fireEvent.click(screen.getByText('Incluir'));
    await waitFor(() => expect(confirmar).toHaveBeenCalledTimes(1));
    const resultado = confirmar.mock.calls[0][0];
    expect(resultado.anexos.map((anexo: { arquivo: Blob }) => anexo.arquivo)).toEqual([pdf, imagem]);
    expect(resultado.ficha.imagemAnexoId).toBe(resultado.anexos[1].id);
    expect(resultado.ficha.pvIniciais).toEqual({ atuais: 7, maximos: 7 });
  });
  test('imagem usa o próprio anexo como retrato e exibe PV indefinidos', async () => {
    const confirmar = jest.fn().mockResolvedValue(true);
    render(<ImportarFicha categoria="monstro" campanhaId="c" onConfirmar={confirmar} onFechar={jest.fn()} />);
    const imagem = new File([new Uint8Array([137, 80, 78, 71, 13, 10, 26, 10])], 'dragao.png', { type: 'image/png' });
    fireEvent.change(screen.getByLabelText(/Arquivo da ficha/), { target: { files: [imagem] } });
    await screen.findByText(/PV não identificados/);
    expect(screen.getByLabelText('Retrato opcional')).toBeInTheDocument();
    await waitFor(() => expect(screen.getByRole('button', {name:'Incluir'})).toBeEnabled());
    fireEvent.click(screen.getByText('Incluir'));
    await waitFor(() => expect(confirmar).toHaveBeenCalledTimes(1));
    const resultado = confirmar.mock.calls[0][0];
    expect(resultado.ficha.imagemAnexoId).toBe(resultado.ficha.anexoId);
    expect(resultado.anexos).toHaveLength(1);
    expect(resultado.anexos[0].arquivo).toBe(imagem);
  });
  test('reconhecimento tardio preserva campos já corrigidos manualmente', async () => {
    let resolver!: (r: {nome:string;pv:{atuais:number;maximos:number};avisos:string[]})=>void;
    (reconhecerArquivo as jest.Mock).mockImplementationOnce(()=>new Promise(resolve=>{resolver=resolve;}));
    render(<ImportarFicha categoria="monstro" campanhaId="c" onConfirmar={jest.fn()} onFechar={jest.fn()}/>);
    fireEvent.change(screen.getByLabelText(/Arquivo da ficha/),{target:{files:[new File(['%PDF-1.7'],'g.pdf',{type:'application/pdf'})]}});
    await screen.findByLabelText('Nome da ficha');
    await waitFor(()=>expect(reconhecerArquivo).toHaveBeenCalled());
    fireEvent.change(screen.getByLabelText('Nome da ficha'),{target:{value:'Nome manual'}});
    fireEvent.change(screen.getByLabelText('PV máximos'),{target:{value:'40'}});
    resolver({nome:'Extraído',pv:{atuais:20,maximos:20},avisos:[]});
    await waitFor(()=>expect(screen.getByRole('button',{name:'Incluir'})).toBeEnabled());
    expect(screen.getByLabelText('Nome da ficha')).toHaveValue('Nome manual');
    expect(screen.getByLabelText('PV máximos')).toHaveValue(40);
    expect(screen.getByLabelText('PV atuais')).toHaveValue(20);
  });
});
