import React from 'react';
import { render, screen, fireEvent } from '@testing-library/react';
import { MemoryRouter } from 'react-router-dom';
import CriarFicha from './criarFicha';
const mockFicha = { nomePersonagem: 'Teste', levelTotal: 4 };
jest.mock('../api/fichaPersonagem/FichaContext', () => ({ useFicha: () => ({ ficha: mockFicha }) }));
jest.mock('./components/CriacaoFicha', () => () => <input aria-label="Escolha em andamento" defaultValue="preservada" />);
jest.mock('./components/InformacoesPersonagem', () => () => <div>Ficha</div>);
jest.mock('./components/PericiasEOutros', () => () => null);
jest.mock('./components/InventarioMagiasDetalhes', () => () => null);
beforeEach(() => localStorage.clear());
test('recolher preserva controles montados e grava apenas preferência visual', () => {
  const antes = JSON.stringify(mockFicha);
  const { unmount } = render(<MemoryRouter future={{ v7_startTransition: true, v7_relativeSplatPath: true }}><CriarFicha /></MemoryRouter>);
  const escolha = screen.getByRole('textbox');
  fireEvent.change(escolha, { target: { value: 'alterada' } });
  fireEvent.click(screen.getByRole('button', { name: 'Recolher progressão' }));
  expect(screen.getByRole('button', { name: 'Expandir progressão' })).toHaveAttribute('aria-expanded', 'false');
  expect(screen.getByRole('button', { name: 'Abrir nível 4' })).toBeVisible();
  expect(localStorage.getItem('progressao-recolhida')).toBe('true');
  expect(JSON.stringify(mockFicha)).toBe(antes);
  fireEvent.click(screen.getByRole('button', { name: 'Expandir progressão' }));
  expect(screen.getByRole('textbox')).toBe(escolha);
  expect(escolha).toHaveValue('alterada');
  fireEvent.click(screen.getByRole('button', { name: 'Recolher progressão' }));
  unmount();
  render(<MemoryRouter future={{ v7_startTransition: true, v7_relativeSplatPath: true }}><CriarFicha /></MemoryRouter>);
  expect(screen.getByRole('button', { name: 'Expandir progressão' })).toHaveAttribute('aria-expanded', 'false');
});
